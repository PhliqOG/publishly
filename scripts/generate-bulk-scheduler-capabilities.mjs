import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..'
);
const matrixPath = path.join(
  repositoryRoot,
  'data',
  'bulk-scheduler-capabilities.json'
);
const outputPath = path.join(
  repositoryRoot,
  'docs',
  'BULK_SCHEDULER_CAPABILITIES.md'
);

const matrix = JSON.parse(await readFile(matrixPath, 'utf8'));

function cell(value) {
  return String(value ?? '—').replaceAll('|', '\\|');
}

function fetchPolicy(tuple) {
  if (tuple.transportMode === 'direct_upload') return 'Internal stream';
  const policy = tuple.providerFetchPolicy;
  if (!policy) return 'Missing (disabled)';
  const fetches =
    policy.maxFetches == null ? 'repeat allowed' : `${policy.maxFetches} max`;
  const methods = [
    policy.allowHead ? 'HEAD' : null,
    policy.allowRange ? 'Range' : null,
  ]
    .filter(Boolean)
    .join('+');
  return `${policy.ttlSeconds}s; ${fetches}; ${methods || 'GET only'}`;
}

const rows = matrix.tuples.map((tuple) => {
  const publicState =
    tuple.defaultEligible &&
    tuple.adapterImplemented &&
    tuple.privateTransportReady &&
    tuple.confirmationImplemented &&
    tuple.ambiguityRecoveryImplemented &&
    tuple.certificationStatus === 'certified' &&
    tuple.certificationEvidence
      ? 'enabled'
      : 'disabled';
  return `| ${cell(tuple.id)} | ${cell(tuple.transportMode)} | ${cell(
    fetchPolicy(tuple)
  )} | ${cell(tuple.confirmationMethod)} | ${cell(
    tuple.ambiguityRecoveryMethod
  )} | ${cell(
    tuple.certificationStatus
  )} | ${publicState} |`;
});

const rendered = `<!-- GENERATED by scripts/generate-bulk-scheduler-capabilities.mjs. Do not edit. -->
# Bulk Scheduler capability matrix

This page is generated from \`data/bulk-scheduler-capabilities.json\`, the only authored source for Bulk Scheduler availability. An absent or unknown tuple is disabled. A tuple is customer-visible only after its adapter, private media transport, live confirmation, ambiguous-mutation recovery, and controlled real-provider canary are all proved and \`defaultEligible\` is explicitly enabled.

Matrix version: **${cell(matrix.schemaVersion)}**  
Last reviewed: **${cell(matrix.updated)}**

| Exact tuple | Media transport | Provider fetch policy | Live confirmation | Ambiguous recovery | Canary | Customer state |
|---|---|---|---|---|---|---|
${rows.join('\n')}

Global rollback control: \`${cell(
  matrix.globalKillSwitchEnv
)}\`. Controlled canaries also require an exact tuple in \`${cell(
  matrix.canaryTupleListEnv
)}\` and an exact designated connection in \`${cell(
  matrix.canaryIntegrationListEnv
)}\`. Each row also has a permanent tuple-specific kill switch in the source matrix.
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = await readFile(outputPath, 'utf8');
  } catch {
    // A missing generated file is drift and intentionally fails below.
  }
  if (current !== rendered) {
    process.stderr.write(
      'Bulk Scheduler capability documentation is stale. Run pnpm generate:bulk-capabilities.\n'
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, rendered, 'utf8');
  process.stdout.write(
    `Generated ${path.relative(repositoryRoot, outputPath)}\n`
  );
}
